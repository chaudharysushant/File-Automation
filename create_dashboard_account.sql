-- Dashboard authentication schema.
--
-- Supports multiple users. Sign-up creates the account directly in
-- dashboard_account; the account can be used to sign in immediately.
--
-- This file is idempotent and migrates the previous single-account table
-- (account_id = 1 with a CHECK constraint) in place.

CREATE TABLE IF NOT EXISTS zph_ftp.dashboard_account (
    account_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL,
    email VARCHAR(254),
    password_hash TEXT NOT NULL,
    reset_token_hash TEXT,
    reset_expires_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Migrate an existing single-account table to the multi-user shape.
ALTER TABLE zph_ftp.dashboard_account DROP CONSTRAINT IF EXISTS dashboard_account_account_id_check;
ALTER TABLE zph_ftp.dashboard_account ADD COLUMN IF NOT EXISTS email VARCHAR(254);
ALTER TABLE zph_ftp.dashboard_account DROP COLUMN IF EXISTS email_verified;
ALTER TABLE zph_ftp.dashboard_account ADD COLUMN IF NOT EXISTS reset_token_hash TEXT;
ALTER TABLE zph_ftp.dashboard_account ADD COLUMN IF NOT EXISTS reset_expires_at TIMESTAMPTZ;
ALTER TABLE zph_ftp.dashboard_account ALTER COLUMN account_id TYPE INTEGER;

-- Give account_id an auto-incrementing default on tables created with the old
-- fixed-value primary key. The sequence is not OWNED BY the column so that the
-- migration also works when the table is owned by a group the deployer belongs
-- to but is not the direct owner of.
CREATE SEQUENCE IF NOT EXISTS zph_ftp.dashboard_account_account_id_seq;
ALTER TABLE zph_ftp.dashboard_account
    ALTER COLUMN account_id SET DEFAULT nextval('zph_ftp.dashboard_account_account_id_seq');
SELECT setval(
    'zph_ftp.dashboard_account_account_id_seq',
    GREATEST((SELECT COALESCE(MAX(account_id), 0) FROM zph_ftp.dashboard_account), 1)
);

CREATE UNIQUE INDEX IF NOT EXISTS dashboard_account_username_lower_key
    ON zph_ftp.dashboard_account (LOWER(username));
CREATE UNIQUE INDEX IF NOT EXISTS dashboard_account_email_lower_key
    ON zph_ftp.dashboard_account (LOWER(email))
    WHERE email IS NOT NULL;

-- Drop the OTP-based registration table, no longer needed.
DROP TABLE IF EXISTS zph_ftp.dashboard_registration;